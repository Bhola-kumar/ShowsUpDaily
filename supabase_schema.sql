-- 1. Settings Table
-- Stores app configuration, OAuth tokens, and schedule state
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

-- 2. Videos Table
-- Stores metadata for uploaded video files
CREATE TABLE IF NOT EXISTS videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename TEXT NOT NULL,
    original_name TEXT,
    title TEXT NOT NULL,
    notes TEXT DEFAULT '',
    uploaded_at TEXT,
    size_bytes BIGINT DEFAULT 0,
    days_posted INTEGER DEFAULT 0,
    first_post_date TEXT
);

-- 3. Posts Table
-- Stores history and status of YouTube uploads
CREATE TABLE IF NOT EXISTS posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT,
    day_no INTEGER,
    posted_at TEXT,
    status TEXT,
    youtube_id TEXT,
    privacy TEXT,
    message TEXT,
    description TEXT,
    tags TEXT
);

-- 4. Storage Bucket for video files
-- Creates the 'videos' storage bucket if it doesn't already exist
INSERT INTO storage.buckets (id, name, public)
VALUES ('videos', 'videos', false)
ON CONFLICT (id) DO NOTHING;

-- Note on Authentication:
-- In your backend deployment, set SUPABASE_KEY to your project's
-- 'service_role' secret key (Project Settings -> API -> service_role).
-- The service_role key automatically bypasses Row Level Security (RLS)
-- and gives full read/write access to both the tables and the storage bucket.

